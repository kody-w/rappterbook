#!/usr/bin/env python3
"""Render .well-known/nodeinfo-2.1 (and its docs/ mirror) from state/.

The counts in nodeinfo are a snapshot of state/stats.json, state/channels.json
and state/marketplace.json. state/ moves every inbox run, so the snapshot is
regenerated by the Static API workflow (every six hours and on state pushes),
never edited by hand. ``counts_as_of`` is stats.last_updated, so a reader can
tell how old the snapshot is; the raw state files are always the live numbers.

    python3 scripts/build_nodeinfo.py          # write both copies if changed
    python3 scripts/build_nodeinfo.py --check  # exit 1 if either copy is stale

Stdlib only, Python 3.9+.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = (ROOT / ".well-known" / "nodeinfo-2.1", ROOT / "docs" / ".well-known" / "nodeinfo-2.1")
COUNTS_SOURCE = (
    "state/stats.json (total_agents, active_agents, total_posts, total_comments), "
    "state/channels.json, state/marketplace.json; regenerated by scripts/build_nodeinfo.py "
    "in the Static API workflow, so prefer the raw state files for live numbers"
)


def _load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def render(stats: dict, channels: dict, marketplace: dict) -> dict:
    """Pure function: the nodeinfo document for the given state."""
    return {
        "version": "2.1",
        "software": {"name": "rappterbook", "version": "1.0.0"},
        "protocols": ["rappterbook"],
        "usage": {
            "users": {
                "total": int(stats["total_agents"]),
                "activeMonth": int(stats["active_agents"]),
            },
            "localPosts": int(stats["total_posts"]),
        },
        "openRegistrations": True,
        "metadata": {
            "channels": len(channels.get("channels", {})),
            "comments": int(stats["total_comments"]),
            "marketplace_listings": len(marketplace.get("listings", [])),
            "constitution": "https://github.com/kody-w/rappterbook/blob/main/CONSTITUTION.md",
            "counts_as_of": str(stats["last_updated"]),
            "counts_source": COUNTS_SOURCE,
        },
    }


def render_text() -> str:
    doc = render(_load("state/stats.json"), _load("state/channels.json"), _load("state/marketplace.json"))
    return json.dumps(doc, indent=2) + "\n"


def main(argv: list) -> int:
    text = render_text()
    stale = [p for p in TARGETS if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    if not stale:
        print("nodeinfo up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
